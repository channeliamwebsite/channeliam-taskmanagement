-- =============================================================================
-- 011_automatic_daily_reports.sql   (additive; existing rows unchanged)
--
-- Daily reports are generated from tasks, not entered by employees:
--
--  * Morning: a scheduled job (pg_cron, every 15 minutes) stores each active
--    member's morning task list once their workspace's local time is past
--    09:00 (Mon–Sat). The snapshot is written only if none exists for that
--    day, so retries never duplicate or overwrite it, and overlapping runs are
--    serialised. Writing it does not change the row's updated_at (the
--    employee's last-edited time).
--  * During the day / evening: public.daily_tracking() compares the morning
--    snapshot with the live task data on every read — tasks added after the
--    morning, current statuses, tasks reassigned or removed — so it is always
--    current and nothing per-task is stored (no duplicates on edits).
--
-- Employee-entered notes and submission times (morning_plan,
-- morning_submitted_at, evening fields from 009) are not touched.
-- Requires 009 (private.workspace_timezone). Works before or after 010 (the
-- write lock-down); the automatic report is written by the database job.
--
-- Re-runnable: an earlier draft of this migration was applied to local
-- development databases, so the statements below tolerate existing objects.
-- =============================================================================

alter table public.daily_reports
  add column if not exists morning_snapshot jsonb
    check (morning_snapshot is null or jsonb_typeof(morning_snapshot) = 'object'),
  add column if not exists morning_generated_at timestamptz;

comment on column public.daily_reports.morning_snapshot is
  'Generated by private.generate_morning_reports; written once per day, never updated: {version, generated_at, timezone, tasks:[{id,title,status,priority,project_name,client_name,scheduled_date,due_date,assigned_at}]}';
comment on column public.daily_reports.morning_generated_at is
  'When the automatic morning report was generated (separate from the employee''s own morning_submitted_at).';
-- No client grants: the columns are written only by the security-definer job.

-- -----------------------------------------------------------------------------
-- A person's tasks for a workday (same rules as My Day / the evening report):
-- open tasks assigned to them that are scheduled for the day or earlier
-- (carried forward), unscheduled but due by the day, or blocked; plus tasks
-- they completed that day (workspace timezone).
-- -----------------------------------------------------------------------------
create or replace function private.daily_task_items(p_workspace_id uuid, p_user_id uuid, p_day date, p_tz text)
returns table (
  task_id uuid,
  title text,
  status text,
  priority text,
  project_name text,
  client_name text,
  scheduled_date date,
  due_date date,
  completed_at timestamptz,
  assigned_at timestamptz
)
language sql stable security definer set search_path = ''
as $$
  select t.id, t.title, t.status::text, t.priority::text, pr.name, coalesce(c.name, pr.client_name),
         t.scheduled_date, t.due_date, t.completed_at, ta.assigned_at
  from public.task_assignees ta
  join public.tasks t on t.id = ta.task_id and t.workspace_id = p_workspace_id
  join public.projects pr on pr.id = t.project_id
  left join public.clients c on c.id = pr.client_id
  where ta.user_id = p_user_id
    and (
      (t.status not in ('COMPLETED', 'CANCELLED')
        and (t.status = 'BLOCKED'
             or t.scheduled_date <= p_day
             or (t.scheduled_date is null and t.due_date <= p_day)))
      or (t.status = 'COMPLETED' and (t.completed_at at time zone p_tz)::date = p_day)
    )
$$;

-- -----------------------------------------------------------------------------
-- Scheduled job: morning snapshots. p_now / p_force / p_workspace_id exist for
-- tests. Returns the number of snapshots written.
-- -----------------------------------------------------------------------------
drop function if exists private.generate_morning_reports(timestamptz, boolean);  -- earlier draft signature

create or replace function private.generate_morning_reports(
  p_now timestamptz default now(),
  p_force boolean default false,
  p_workspace_id uuid default null
)
returns integer
language plpgsql security definer set search_path = ''
as $$
declare
  v_count integer;
begin
  -- Overlapping runs (a slow run still going when the next one starts, or a
  -- manual run) wait for each other. The insert below takes its snapshot after
  -- the lock, so a later run sees what the earlier one committed and skips it;
  -- the unique key and the ON CONFLICT guard are the second line of defence.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('private.generate_morning_reports'));

  with ws as (
    select w.id, z.tz,
           (p_now at time zone z.tz)::date as local_date,
           (p_now at time zone z.tz)::time as local_time
    from public.workspaces w
    cross join lateral (select private.workspace_timezone(w.id) as tz) z
    where p_workspace_id is null or w.id = p_workspace_id
  ),
  due as (
    select ws.id as workspace_id, ws.tz, ws.local_date, wm.user_id, p.team
    from ws
    join public.workspace_members wm on wm.workspace_id = ws.id
    join public.profiles p on p.id = wm.user_id and p.is_active
    where (p_force or (ws.local_time >= time '09:00' and extract(isodow from ws.local_date) <> 7))
      and not exists (
        select 1 from public.daily_reports r
        where r.user_id = wm.user_id and r.workspace_id = ws.id and r.report_date = ws.local_date
          and r.morning_snapshot is not null
      )
  )
  insert into public.daily_reports as r
    (user_id, workspace_id, report_date, morning_snapshot, morning_generated_at, reporter_team)
  select d.user_id, d.workspace_id, d.local_date,
         jsonb_build_object(
           'version', 1,
           'generated_at', p_now,
           'timezone', d.tz,
           'tasks', coalesce((
             select jsonb_agg(jsonb_build_object(
                      'id', i.task_id, 'title', i.title, 'status', i.status, 'priority', i.priority,
                      'project_name', i.project_name, 'client_name', i.client_name,
                      'scheduled_date', i.scheduled_date, 'due_date', i.due_date, 'assigned_at', i.assigned_at
                    ) order by i.due_date nulls last, i.title)
             from private.daily_task_items(d.workspace_id, d.user_id, d.local_date, d.tz) i
             where i.status <> 'COMPLETED'
           ), '[]'::jsonb)
         ),
         p_now,
         d.team
  from due d
  on conflict (user_id, workspace_id, report_date) do update
    set morning_snapshot     = excluded.morning_snapshot,
        morning_generated_at = excluded.morning_generated_at,
        reporter_team        = coalesce(r.reporter_team, excluded.reporter_team)
    where r.morning_snapshot is null;  -- never overwrite an existing snapshot

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

-- -----------------------------------------------------------------------------
-- Writing the automatic snapshot is not an edit by the employee: keep the
-- row's updated_at (shown as "last saved / last updated" next to the
-- employee's own submission times). Runs after set_updated_at, because
-- triggers on the same event fire in name order.
-- -----------------------------------------------------------------------------
create or replace function private.keep_updated_at_for_generated_snapshot()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if (to_jsonb(new) - array['morning_snapshot', 'morning_generated_at', 'reporter_team', 'updated_at'])
     = (to_jsonb(old) - array['morning_snapshot', 'morning_generated_at', 'reporter_team', 'updated_at']) then
    new.updated_at := old.updated_at;
  end if;
  return new;
end;
$$;

drop trigger if exists set_updated_at_keep_for_snapshot on public.daily_reports;
create trigger set_updated_at_keep_for_snapshot before update on public.daily_reports
  for each row execute function private.keep_updated_at_for_generated_snapshot();

-- -----------------------------------------------------------------------------
-- Live daily tracking for today (workspace timezone): every relevant task per
-- person, compared with that person's morning snapshot.
--   tracking: MORNING    in the morning report and still today's work
--             CURRENT    today's work; no morning report exists yet
--   today's work that is not in the morning report, by the recorded times
--   (tasks.created_at, task_assignees.assigned_at, tasks.completed_at)
--   compared with the report's generation time:
--             COMPLETED_EARLY  completed before the report was generated
--                              (the report lists open work only)
--             ADDED      task created after the report
--             ASSIGNED   existing task assigned to them after the report
--             MOVED_IN   existing task, already theirs, that joined today's
--                        list after the report (rescheduled, reopened, newly
--                        due); when it changed is not recorded, so no time is shown
--             REASSIGNED in the morning report, no longer assigned to them
--             CHANGED    in the morning report, still theirs, no longer today's
--                        work (e.g. rescheduled or cancelled)
--             REMOVED    in the morning report, task no longer exists
-- Super admins and admins see every member of the workspace (the same reach
-- as the daily_reports read policy); everyone else sees only themselves.
-- -----------------------------------------------------------------------------
create or replace function public.daily_tracking(p_workspace_id uuid)
returns table (
  user_id uuid,
  task_id uuid,
  title text,
  status text,
  priority text,
  project_name text,
  client_name text,
  scheduled_date date,
  due_date date,
  completed_at timestamptz,
  assigned_at timestamptz,
  morning_status text,
  tracking text,
  morning_generated_at timestamptz,
  evening_submitted_at timestamptz
)
language plpgsql stable security definer set search_path = ''
as $$
#variable_conflict use_column
declare
  v_uid uuid := (select auth.uid());
  v_tz text;
  v_day date;
  v_all boolean;
begin
  if v_uid is null or p_workspace_id is null or not private.is_active_workspace_member(p_workspace_id, v_uid) then
    raise exception 'Not permitted' using errcode = '42501';
  end if;
  v_tz := private.workspace_timezone(p_workspace_id);
  v_day := (now() at time zone v_tz)::date;
  v_all := private.has_workspace_role(p_workspace_id, array['SUPER_ADMIN', 'ADMIN']::public.user_role[]);

  return query
  with people as (
    select wm.user_id as uid
    from public.workspace_members wm
    where wm.workspace_id = p_workspace_id and (v_all or wm.user_id = v_uid)
  ),
  report as (
    select r.user_id as uid, r.morning_snapshot, r.morning_generated_at, r.evening_submitted_at
    from public.daily_reports r
    where r.workspace_id = p_workspace_id and r.report_date = v_day and r.user_id in (select uid from people)
  ),
  morning as (
    select rp.uid, (e ->> 'id')::uuid as tid, e ->> 'status' as m_status, e ->> 'title' as m_title,
           e ->> 'priority' as m_priority, e ->> 'project_name' as m_project, e ->> 'client_name' as m_client
    from report rp
    cross join lateral jsonb_array_elements(coalesce(rp.morning_snapshot -> 'tasks', '[]'::jsonb)) e
    where rp.morning_snapshot is not null
  ),
  live as (
    select p.uid, i.*
    from people p
    cross join lateral private.daily_task_items(p_workspace_id, p.uid, v_day, v_tz) i
  )
  select l.uid, l.task_id, l.title, l.status, l.priority, l.project_name, l.client_name,
         l.scheduled_date, l.due_date, l.completed_at, l.assigned_at,
         m.m_status,
         case when m.tid is not null then 'MORNING'
              when rp.morning_snapshot is null then 'CURRENT'
              when l.status = 'COMPLETED' and l.completed_at <= rp.morning_generated_at then 'COMPLETED_EARLY'
              when tc.created_at > rp.morning_generated_at then 'ADDED'
              when l.assigned_at > rp.morning_generated_at then 'ASSIGNED'
              else 'MOVED_IN' end,
         rp.morning_generated_at, rp.evening_submitted_at
  from live l
  join public.tasks tc on tc.id = l.task_id
  left join morning m on m.uid = l.uid and m.tid = l.task_id
  left join report rp on rp.uid = l.uid
  union all
  select m.uid, m.tid, coalesce(t.title, m.m_title), t.status::text, coalesce(t.priority::text, m.m_priority),
         coalesce(pr.name, m.m_project), coalesce(c.name, pr.client_name, m.m_client),
         t.scheduled_date, t.due_date, t.completed_at,
         (select ta.assigned_at from public.task_assignees ta where ta.task_id = m.tid and ta.user_id = m.uid),
         m.m_status,
         case when t.id is null then 'REMOVED'
              when not exists (select 1 from public.task_assignees ta where ta.task_id = m.tid and ta.user_id = m.uid) then 'REASSIGNED'
              else 'CHANGED' end,
         rp.morning_generated_at, rp.evening_submitted_at
  from morning m
  join report rp on rp.uid = m.uid
  left join public.tasks t on t.id = m.tid
  left join public.projects pr on pr.id = t.project_id
  left join public.clients c on c.id = pr.client_id
  where not exists (select 1 from live l where l.uid = m.uid and l.task_id = m.tid);
end;
$$;

-- -----------------------------------------------------------------------------
-- Privileges
-- -----------------------------------------------------------------------------
revoke all on function
  private.daily_task_items(uuid, uuid, date, text),
  private.generate_morning_reports(timestamptz, boolean, uuid),
  private.keep_updated_at_for_generated_snapshot()
from public, anon, authenticated;

revoke all on function public.daily_tracking(uuid) from public, anon;
grant execute on function public.daily_tracking(uuid) to authenticated;

-- -----------------------------------------------------------------------------
-- Schedule (same mechanism as the 006 reminder job; cron.schedule replaces a
-- job with the same name). Without pg_cron the function must be run by another
-- scheduler with database access:
--   select private.generate_morning_reports();
-- -----------------------------------------------------------------------------
do $$
begin
  if exists (select 1 from pg_available_extensions where name = 'pg_cron') then
    create extension if not exists pg_cron with schema pg_catalog;
    perform cron.schedule('daily-morning-reports', '*/15 * * * *', 'select private.generate_morning_reports()');
  else
    raise notice 'pg_cron is not available; schedule "select private.generate_morning_reports()" every 15 minutes.';
  end if;
end;
$$;
